"""Generate the frontend permission constants from the backend registry.

    python scripts/export_permissions.py [output_path]

The registry in app/core/permission_registry.py is the single source of
truth; the frontend imports the generated file instead of hard-coding
permission strings.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.core.permission_registry import PERMISSIONS, REGISTRY_VERSION, SCOPE_LABELS, Scope  # noqa: E402

DEFAULT_OUT = ROOT.parent / "hrms-frontend" / "src" / "lib" / "permissions.generated.ts"


def render() -> str:
    lines = [
        "// AUTO-GENERATED by hrms-backend/scripts/export_permissions.py - do not edit by hand.",
        "// Source of truth: hrms-backend/app/core/permission_registry.py",
        "",
        f'export const REGISTRY_VERSION = "{REGISTRY_VERSION}";',
        "",
        "export const P = {",
    ]
    for perm in PERMISSIONS:
        key = perm.code.replace(":", "_").upper()
        lines.append(f'  {key}: "{perm.code}",')
    lines += [
        "} as const;",
        "",
        "export type PermissionCode = (typeof P)[keyof typeof P];",
        "",
        "export const SCOPES = [" + ", ".join(f'"{s.value}"' for s in Scope) + "] as const;",
        "export type Scope = (typeof SCOPES)[number];",
        "",
        "export const SCOPE_LABELS: Record<Scope, string> = "
        + json.dumps({s.value: SCOPE_LABELS[s] for s in Scope}, indent=2)
        + ";",
        "",
        "export interface PermissionMeta {",
        "  module: string;",
        "  label: string;",
        "  description: string;",
        '  sensitivity: "standard" | "confidential" | "restricted";',
        "  scopes: Scope[];",
        "}",
        "",
        "export const PERMISSION_META: Record<PermissionCode, PermissionMeta> = "
        + json.dumps(
            {
                p.code: {
                    "module": p.module,
                    "label": p.label,
                    "description": p.description,
                    "sensitivity": p.sensitivity,
                    "scopes": [s.value for s in p.scopes],
                }
                for p in PERMISSIONS
            },
            indent=2,
        )
        + " as Record<PermissionCode, PermissionMeta>;",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8")
    print(f"Wrote {len(PERMISSIONS)} permissions to {out}")


if __name__ == "__main__":
    main()
