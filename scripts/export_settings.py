"""Generate the frontend settings catalogue from the backend registry (3.1 §2.1).

    python scripts/export_settings.py [output_path]

app/payroll/settings_registry.py and app/payroll/policy_types.py are the single source of
truth: keys, types, defaults, levels, sections, labels, help, constraints, dependencies, grains,
flags, aliases, configuration profiles and policy field metadata. The frontend imports the
generated file instead of hard-coding them. Only those pure modules are imported, so no
database, environment variables or application settings are needed. The output is
deterministic: running the script twice produces the same file.
"""

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.payroll.policy_types import policy_type_metadata  # noqa: E402
from app.payroll.settings_registry import (  # noqa: E402
    ALIASES,
    GRAINS,
    PRECEDENCE,
    PROFILES,
    REGISTRY_VERSION,
    SCOPE_LEVELS,
    SECTIONS,
    SETTING_TYPES,
    definition_json,
    definitions,
    registry_fingerprint,
)

DEFAULT_OUT = ROOT.parent / "hrms-frontend" / "src" / "lib" / "settings.generated.ts"


def _json(value: Any) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False)


def _union(values: Any) -> str:
    return " | ".join(f'"{v}"' for v in values)


def render() -> str:
    defs = definitions()
    keys = [d.key for d in defs]
    profiles = [
        {
            "name": p.name,
            "source": p.source,
            "reason": p.reason,
            "description": p.description,
            "locks": sorted(p.locks),
            "decisions": dict(p.decisions),
            "policies": [{"type": pp.type, "name": pp.name, "note": pp.note} for pp in p.policies],
            "acknowledgments": list(p.acknowledgments),
        }
        for p in PROFILES.values()
    ]
    lines = [
        "// AUTO-GENERATED by hrms-backend/scripts/export_settings.py - do not edit by hand.",
        "// Source of truth: hrms-backend/app/payroll/settings_registry.py and app/payroll/policy_types.py",
        "",
        f'export const SETTINGS_REGISTRY_VERSION = "{REGISTRY_VERSION}";',
        f'export const SETTINGS_FINGERPRINT = "{registry_fingerprint()}";',
        "",
        f"export type SettingLevel = {_union(lv.value for lv in PRECEDENCE)};",
        f"export type ScopeLevel = {_union(lv.value for lv in SCOPE_LEVELS)};",
        "/** Most specific first: the first value found wins, unless a broader level locked it. */",
        f"export const PRECEDENCE: SettingLevel[] = {_json([lv.value for lv in PRECEDENCE])};",
        f"export const SCOPE_LEVELS: ScopeLevel[] = {_json([lv.value for lv in SCOPE_LEVELS])};",
        f"export type SettingType = {_union(sorted(SETTING_TYPES))};",
        f"export type ResolutionGrain = {_union(GRAINS)};",
        'export type SupportStatus = "NOT_IMPLEMENTED" | "BETA" | "SUPPORTED";',
        'export type LegalSensitivity = "NONE" | "LEGAL_FLOOR" | "STATUTORY";',
        "",
        "export interface SettingSection {",
        "  slug: string;",
        "  title: string;",
        "  spec: string;",
        "  policyTypes: string[];",
        "}",
        "",
        "/** Settings › Payroll pages in display order (3.8 §3.1). */",
        "export const SETTING_SECTIONS: SettingSection[] = "
        + _json([{"slug": s.slug, "title": s.title, "spec": s.spec, "policyTypes": list(s.policy_types)}
                 for s in SECTIONS])
        + ";",
        "",
        f"export const SETTING_KEYS = {_json(keys)} as const;",
        "export type SettingKey = (typeof SETTING_KEYS)[number];",
        "",
        "export interface SettingDefinition {",
        "  key: SettingKey;",
        "  type: SettingType;",
        "  /** PLATFORM default in JSON form; null when it is derived from context (see derivedDefault). */",
        "  default: unknown;",
        "  derivedDefault: { source: string; description: string } | null;",
        "  allowedLevels: ScopeLevel[];",
        "  module: string;",
        "  section: string;",
        "  sectionSlug: string;",
        "  label: string;",
        "  help: string;",
        "  constraints: Record<string, unknown>;",
        "  dependsOn: SettingKey[];",
        "  resolutionGrain: ResolutionGrain;",
        "  effectiveDated: boolean;",
        '  sensitivity: "standard" | "confidential" | "restricted";',
        "  requiresApproval: boolean;",
        "  adminOnly: boolean;",
        "  lockable: boolean;",
        "  statutoryScheme: string | null;",
        "  aliases: string[];",
        "  ui: Record<string, unknown>;",
        "  /** STARTER_V1 value for newly provisioned tenants (JSON form). */",
        "  newTenantDefault: unknown;",
        "  supportStatus: SupportStatus;",
        "  legalSensitivity: LegalSensitivity;",
        "  decisionRequired: boolean;",
        "  failsClosed: boolean;",
        "}",
        "",
        "export const SETTING_DEFINITIONS: Record<SettingKey, SettingDefinition> = "
        + _json({d.key: definition_json(d) for d in defs})
        + " as Record<SettingKey, SettingDefinition>;",
        "",
        "/** Legacy key -> registry key (3.1 §2.4). */",
        "export const SETTING_ALIASES: Record<string, SettingKey> = "
        + _json(dict(sorted(ALIASES.items())))
        + " as Record<string, SettingKey>;",
        "",
        "export interface PolicyFieldMeta {",
        "  name: string;",
        "  kind: string;",
        "  default?: unknown;",
        "  required?: boolean;",
        "  nullable?: boolean;",
        "  help?: string;",
        "  legal_sensitivity: LegalSensitivity;",
        "  [constraint: string]: unknown;",
        "}",
        "",
        "export interface PolicyTypeMeta {",
        "  code: string;",
        "  label: string;",
        "  gateSwitches: SettingKey[];",
        "  grain: ResolutionGrain;",
        "  section: string;",
        "  spec: string;",
        "  assignable: boolean;",
        "  fields: PolicyFieldMeta[];",
        "}",
        "",
        "export const POLICY_TYPES: PolicyTypeMeta[] = " + _json(policy_type_metadata()) + " as PolicyTypeMeta[];",
        "",
        "export interface SettingsProfile {",
        "  name: string;",
        "  source: string;",
        "  reason: string;",
        "  description: string;",
        "  locks: SettingKey[];",
        "  decisions: Partial<Record<SettingKey, string>>;",
        "  policies: { type: string; name: string; note: string | null }[];",
        "  acknowledgments: string[];",
        "}",
        "",
        "export const SETTINGS_PROFILES: SettingsProfile[] = " + _json(profiles) + " as SettingsProfile[];",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {len(definitions())} settings and {len(policy_type_metadata())} policy types to {out}")


if __name__ == "__main__":
    main()
