"""Increment cycles (bulk revisions, 3.3 §8.2, 3.8 §5.7): population -> method -> preview -> approve -> apply.

* Population filters (legal entities, departments, grades, employees, hire dates) select active employees
  placed on the effective date inside the caller's payroll:compensation:edit scope; employees without a
  salary in force on that date are listed as EXCLUDED.
* Methods: PERCENT {percent}, FIXED_AMOUNT {amounts: {currency: amount}}, PER_ROW {rows: [{employee_id |
  employee_code, pay_basis_amount}]} and MATRIX {matrix: {grade code: {rating: percent}}, ratings:
  {employee_id: rating}, default_percent}; an optional structure_version_id moves everyone to that
  published version. New amounts are rounded to the currency's minor unit.
* The preview stores one item per employee (old, new, change %, grade-range position) and totals per
  currency. Submitting routes the cycle through the approvals engine (module "compensation"); the maker
  cannot approve and an approver inside the population cannot approve their own increment. Applying an
  approved cycle re-validates each item and puts the new salaries in force (reason REVISION, approved by
  the cycle's approver); an item that no longer validates is FAILED with the reason, the rest apply.

Increment letters (3.6 §11) are generated by the documents milestone from APPLIED items.
"""

