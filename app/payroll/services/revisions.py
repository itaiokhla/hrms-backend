READ = comp_service.READ
EDIT = comp_service.EDIT
SUBJECT = "revision_cycle"
METHODS = ("PERCENT", "FIXED_AMOUNT", "PER_ROW", "MATRIX")
POPULATION_KEYS = ("legal_entity_ids", "department_ids", "grade_ids", "employee_ids", "hire_date_before",
                   "hire_date_after")
MAX_ITEMS = 5000

REVISION_CYCLE_CREATED = "REVISION_CYCLE_CREATED"
REVISION_CYCLE_PREVIEWED = "REVISION_CYCLE_PREVIEWED"
REVISION_CYCLE_SUBMITTED = "REVISION_CYCLE_SUBMITTED"
REVISION_CYCLE_APPROVED = "REVISION_CYCLE_APPROVED"
REVISION_CYCLE_REJECTED = "REVISION_CYCLE_REJECTED"
REVISION_CYCLE_APPLIED = "REVISION_CYCLE_APPLIED"
REVISION_CYCLE_CANCELLED = "REVISION_CYCLE_CANCELLED"


def _audit(db: Session, principal: Principal | None, action: str, description: str, cycle: RevisionCycle,
           **details: Any) -> None:
    AuditLogService.log(db, principal, payroll_audit.COMPENSATION, action, description, "revision_cycle", cycle.id,
                        company_id=cycle.company_id, actor_type="user" if principal else "system",
                        details={"name": cycle.name, **details})


def _load(db: Session, principal: Principal, cycle_id: int, *, lock: bool = False) -> RevisionCycle:
    if not principal.has(EDIT):
        raise forbidden()
    query = db.query(RevisionCycle).filter(RevisionCycle.company_id == principal.company_id,
                                           RevisionCycle.id == cycle_id)
    if lock:
        query = query.with_for_update()
    cycle = query.first()
    if cycle is None:
        raise not_found("Revision cycle")
    return cycle


def _ids(raw: Any, what: str) -> list[int]:
    if not isinstance(raw, list) or any(isinstance(i, bool) or not isinstance(i, int) for i in raw):
        raise comp.invalid(f"population.{what} is a list of ids.", "INVALID_POPULATION", "population")
    return sorted(set(raw))


def _population(raw: Mapping[str, Any] | None) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in (raw or {}).items():
        if key not in POPULATION_KEYS:
            raise comp.invalid(f"population has an unknown filter {key!r}.", "INVALID_POPULATION", "population")
        if key.startswith("hire_date"):
            try:
                result[key] = dt.date.fromisoformat(str(value)).isoformat()
            except ValueError:
                raise comp.invalid(f"population.{key} is a date.", "INVALID_POPULATION", "population")
        else:
            result[key] = _ids(value, key)
    return result


def _method(db: Session, company_id: int, raw: Mapping[str, Any]) -> dict[str, Any]:
    kind = raw.get("type")
    if kind not in METHODS:
        raise comp.invalid(f"method.type is one of {', '.join(METHODS)}.", "INVALID_METHOD", "method")
    method: dict[str, Any] = {"type": kind}
    allowed = {"type", "structure_version_id", "percent", "amounts", "rows", "matrix", "ratings", "default_percent"}
    if set(raw) - allowed:
        raise comp.invalid(f"method has unknown keys: {', '.join(sorted(set(raw) - allowed))}.", "INVALID_METHOD",
                           "method")
    if raw.get("structure_version_id") is not None:
        version = db.query(SalaryTemplateVersion).filter(SalaryTemplateVersion.company_id == company_id,
                                                         SalaryTemplateVersion.id == raw["structure_version_id"]).first()
        if version is None or version.status != "ACTIVE":
            raise comp.invalid("structure_version_id must be a published structure version.", "STRUCTURE_NOT_ACTIVE",
                               "method")
        method["structure_version_id"] = version.id
    if kind == "PERCENT":
        method["percent"] = decimal_str(comp.parse_decimal(raw.get("percent"), "method.percent", allow_negative=True))
    elif kind == "FIXED_AMOUNT":
        amounts = raw.get("amounts")
        if not isinstance(amounts, Mapping) or not amounts:
            raise comp.invalid("FIXED_AMOUNT needs amounts per currency: {\"INR\": \"5000\"}.", "INVALID_METHOD",
                               "method")
        method["amounts"] = {str(cur): decimal_str(comp.parse_decimal(v, f"amounts.{cur}", allow_negative=True))
                             for cur, v in amounts.items()}
    elif kind == "PER_ROW":
        rows = raw.get("rows")
        if not isinstance(rows, list) or not rows or len(rows) > MAX_ITEMS:
            raise comp.invalid("PER_ROW needs rows [{employee_id | employee_code, pay_basis_amount}].",
                               "INVALID_METHOD", "method")
        cleaned = []
        for item in rows:
            if not isinstance(item, Mapping) or "pay_basis_amount" not in item or not (
                    item.get("employee_id") or item.get("employee_code")):
                raise comp.invalid("Each row names an employee and a pay_basis_amount.", "INVALID_METHOD", "method")
            cleaned.append({"employee_id": item.get("employee_id"), "employee_code": item.get("employee_code"),
                            "pay_basis_amount": decimal_str(comp.parse_decimal(item["pay_basis_amount"],
                                                                               "pay_basis_amount"))})
        method["rows"] = cleaned
    else:
        matrix = raw.get("matrix")
        if not isinstance(matrix, Mapping) or not matrix:
            raise comp.invalid("MATRIX needs {grade code: {rating: percent}}.", "INVALID_METHOD", "method")
        method["matrix"] = {str(grade): {str(rating): decimal_str(comp.parse_decimal(pct, "matrix", allow_negative=True))
                                         for rating, pct in (ratings or {}).items()} for grade, ratings in matrix.items()}
        method["ratings"] = {str(k): str(v) for k, v in (raw.get("ratings") or {}).items()}
        method["default_percent"] = decimal_str(comp.parse_decimal(raw.get("default_percent", "0"),
                                                                   "default_percent", allow_negative=True))
    return method


def cycle_json(db: Session, cycle: RevisionCycle, *, items: bool = False) -> dict[str, Any]:
    data = {
        "id": cycle.id, "name": cycle.name, "population": cycle.population, "method": cycle.method,
        "effective_from": cycle.effective_from, "status": cycle.status, "totals": cycle.totals,
        "approval_request_id": cycle.approval_request_id, "row_version": cycle.row_version,
        "created_by_user_id": cycle.created_by_user_id, "applied_by_user_id": cycle.applied_by_user_id,
        "applied_at": cycle.applied_at, "created_at": cycle.created_at,
    }
    if items:
        rows = (db.query(RevisionCycleItem, Employee)
                .join(Employee, Employee.id == RevisionCycleItem.employee_id)
                .filter(RevisionCycleItem.company_id == cycle.company_id, RevisionCycleItem.cycle_id == cycle.id)
                .order_by(Employee.first_name, RevisionCycleItem.id).all())
        data["items"] = [{"id": item.id, "employee": comp_service._employee_ref(employee), "status": item.status,
                          "old_assignment_id": item.old_assignment_id, "new_assignment_id": item.new_assignment_id,
                          "proposed": item.proposed, "note": item.note} for item, employee in rows]
    return data


def list_cycles(db: Session, principal: Principal) -> list[dict[str, Any]]:
    if not principal.has(EDIT) and not principal.has(comp_service.APPROVE):
        raise forbidden()
    rows = (db.query(RevisionCycle).filter(RevisionCycle.company_id == principal.company_id)
            .order_by(RevisionCycle.created_at.desc()).all())
    return [cycle_json(db, row) for row in rows]


def get_cycle(db: Session, principal: Principal, cycle_id: int) -> dict[str, Any]:
    if not principal.has(EDIT) and not principal.has(comp_service.APPROVE):
        raise forbidden()
    cycle = db.query(RevisionCycle).filter(RevisionCycle.company_id == principal.company_id,
                                           RevisionCycle.id == cycle_id).first()
    if cycle is None:
        raise not_found("Revision cycle")
    return cycle_json(db, cycle, items=True)


def create_cycle(db: Session, principal: Principal, *, name: str, population: Mapping[str, Any] | None,
                 method: Mapping[str, Any], effective_from: dt.date) -> dict[str, Any]:
    if not principal.has(EDIT):
        raise forbidden()
    name = (name or "").strip()
    if not 1 <= len(name) <= 150:
        raise comp.invalid("The cycle name must be 1-150 characters.", "INVALID_NAME", "name")
    cycle = RevisionCycle(company_id=principal.company_id, name=name, population=_population(population),
                          method=_method(db, principal.company_id, method), effective_from=effective_from,
                          status="DRAFT", row_version=1, created_by_user_id=principal.user_id)
    db.add(cycle)
    db.flush()
    _audit(db, principal, REVISION_CYCLE_CREATED, f"Created the revision cycle {name}", cycle,
           method=cycle.method["type"], effective_from=effective_from.isoformat())
    return cycle_json(db, cycle, items=True)


def update_cycle(db: Session, principal: Principal, cycle_id: int, *, row_version: int | None,
                 name: str | None = None, population: Mapping[str, Any] | None = None,
                 method: Mapping[str, Any] | None = None, effective_from: dt.date | None = None) -> dict[str, Any]:
    cycle = _load(db, principal, cycle_id, lock=True)
    if cycle.status not in ("DRAFT", "PREVIEWED"):
        raise conflict(f"A {cycle.status.lower()} cycle cannot change.", "CYCLE_LOCKED")
    if row_version is not None and row_version != cycle.row_version:
        raise conflict("This cycle changed since you loaded it.", "ROW_VERSION_CONFLICT")
    if name is not None:
        if not 1 <= len(name.strip()) <= 150:
            raise comp.invalid("The cycle name must be 1-150 characters.", "INVALID_NAME", "name")
        cycle.name = name.strip()
    if population is not None:
        cycle.population = _population(population)
    if method is not None:
        cycle.method = _method(db, principal.company_id, method)
    if effective_from is not None:
        cycle.effective_from = effective_from
    cycle.status = "DRAFT"
    cycle.totals = None
    cycle.row_version += 1
    db.query(RevisionCycleItem).filter(RevisionCycleItem.company_id == cycle.company_id,
                                       RevisionCycleItem.cycle_id == cycle.id).delete(synchronize_session=False)
    db.flush()
    return cycle_json(db, cycle, items=True)


# --------------------------------------------------------------------------- preview
def _population_employees(db: Session, principal: Principal, cycle: RevisionCycle) -> list[Employee]:
    cid = principal.company_id
    on = cycle.effective_from
    filters = cycle.population or {}
    placement = (db.query(EmployeeAssignment.employee_id)
                 .filter(EmployeeAssignment.company_id == cid, EmployeeAssignment.is_primary.is_(True),
                         EmployeeAssignment.effective_from <= on,
                         or_(EmployeeAssignment.effective_to.is_(None), EmployeeAssignment.effective_to >= on)))
    if filters.get("legal_entity_ids"):
        placement = placement.filter(EmployeeAssignment.legal_entity_id.in_(filters["legal_entity_ids"]))
    if filters.get("grade_ids"):
        placement = placement.filter(EmployeeAssignment.grade_id.in_(filters["grade_ids"]))
    if filters.get("department_ids"):
        placement = placement.filter(EmployeeAssignment.department_id.in_(filters["department_ids"]))
    query = db.query(Employee).filter(
        Employee.company_id == cid, Employee.is_active.is_(True), Employee.id.in_(placement),
        or_(Employee.termination_date.is_(None), Employee.termination_date >= on),
        comp_service._scope_clause(db, principal, EDIT, on, on, Employee.id))
    if filters.get("employee_ids"):
        query = query.filter(Employee.id.in_(filters["employee_ids"]))
    if filters.get("hire_date_before"):
        query = query.filter(Employee.hire_date <= dt.date.fromisoformat(filters["hire_date_before"]))
    if filters.get("hire_date_after"):
        query = query.filter(Employee.hire_date >= dt.date.fromisoformat(filters["hire_date_after"]))
    employees = query.order_by(Employee.id).limit(MAX_ITEMS + 1).all()
    if len(employees) > MAX_ITEMS:
        raise bad_request(f"A cycle covers at most {MAX_ITEMS} employees; narrow the population.", "CYCLE_TOO_LARGE")
    return employees


def _new_amount(db: Session, cycle: RevisionCycle, employee: Employee, current: CompensationAssignment
                ) -> tuple[Decimal | None, str | None]:
    method = cycle.method
    old = Decimal(current.pay_basis_amount)
    currency = current.currency
    kind = method["type"]

    def percent(pct: Decimal) -> Decimal:
        return quantize_amount(old * (1 + pct / 100), currency, "HALF_UP")

    if kind == "PERCENT":
        return percent(Decimal(method["percent"])), None
    if kind == "FIXED_AMOUNT":
        amount = method["amounts"].get(currency)
        if amount is None:
            return None, f"No increment amount is set for {currency}."
        return old + Decimal(amount), None
    if kind == "PER_ROW":
        row = next((r for r in method["rows"] if r.get("employee_id") == employee.id or
                    (r.get("employee_code") and r.get("employee_code") == employee.employee_code)), None)
        if row is None:
            return None, "The employee has no row in the file."
        return Decimal(row["pay_basis_amount"]), None
    placement = comp_service.placement_on(db, cycle.company_id, employee.id, cycle.effective_from)
    grade = db.get(Grade, placement.grade_id) if placement is not None and placement.grade_id else None
    rating = method["ratings"].get(str(employee.id))
    pct = (method["matrix"].get(grade.code) or {}).get(rating) if grade is not None and rating is not None else None
    return percent(Decimal(pct if pct is not None else method["default_percent"])), None


def preview_cycle(db: Session, principal: Principal, cycle_id: int) -> dict[str, Any]:
    """(Re)build the items and totals per currency (old, new, change %, grade-range position)."""
    cycle = _load(db, principal, cycle_id, lock=True)
    if cycle.status not in ("DRAFT", "PREVIEWED"):
        raise conflict(f"A {cycle.status.lower()} cycle cannot be previewed again.", "CYCLE_LOCKED")
    cid = principal.company_id
    db.query(RevisionCycleItem).filter(RevisionCycleItem.company_id == cid,
                                       RevisionCycleItem.cycle_id == cycle.id).delete(synchronize_session=False)
    totals: dict[str, dict[str, Any]] = {}
    for employee in _population_employees(db, principal, cycle):
        current = comp_service.in_force_row(db, cid, employee.id, cycle.effective_from)
        item = RevisionCycleItem(company_id=cid, cycle_id=cycle.id, employee_id=employee.id, status="PROPOSED")
        if current is None:
            item.status, item.note = "EXCLUDED", "No salary in force on the effective date."
            db.add(item)
            continue
        item.old_assignment_id = current.id
        new, problem = _new_amount(db, cycle, employee, current)
        if new is None:
            item.status, item.note = "EXCLUDED", problem
            db.add(item)
            continue
        if new < 0:
            item.status, item.note = "EXCLUDED", "The new amount would be negative."
            db.add(item)
            continue
        version_id = cycle.method.get("structure_version_id") or current.template_version_id
        version = db.get(SalaryTemplateVersion, version_id)
        template = comp_service._template(db, version)
        placement = comp_service.placement_on(db, cid, employee.id, cycle.effective_from)
        grade = comp_service.grade_range_check(db, cid, placement, template.type, new, current.currency)
        old = Decimal(current.pay_basis_amount)
        item.proposed = {
            "template_version_id": version_id, "currency": current.currency,
            "old_pay_basis_amount": amount_str(old, current.currency),
            "pay_basis_amount": amount_str(new, current.currency),
            "change_pct": comp_service._change_pct(old, new), "grade_range": grade["status"],
            "position_pct": grade["position_pct"],
        }
        db.add(item)
        bucket = totals.setdefault(current.currency, {"count": 0, "old": Decimal(0), "new": Decimal(0)})
        bucket["count"] += 1
        bucket["old"] += old
        bucket["new"] += new
    cycle.totals = {cur: {"count": t["count"], "old": amount_str(t["old"], cur), "new": amount_str(t["new"], cur),
                          "increase": amount_str(t["new"] - t["old"], cur),
                          "change_pct": comp_service._change_pct(t["old"], t["new"])} for cur, t in totals.items()}
    cycle.status = "PREVIEWED"
    cycle.row_version += 1
    db.flush()
    _audit(db, principal, REVISION_CYCLE_PREVIEWED, f"Previewed the revision cycle {cycle.name}", cycle,
           employees=sum(t["count"] for t in totals.values()), currencies=sorted(totals))
    return cycle_json(db, cycle, items=True)


# --------------------------------------------------------------------------- approval
def submit_cycle(db: Session, principal: Principal, cycle_id: int) -> dict[str, Any]:
    cycle = _load(db, principal, cycle_id, lock=True)
    if cycle.status != "PREVIEWED":
        raise conflict("Preview the cycle before submitting it.", "CYCLE_NOT_PREVIEWED")
    proposed = db.query(RevisionCycleItem.id).filter(RevisionCycleItem.company_id == cycle.company_id,
                                                     RevisionCycleItem.cycle_id == cycle.id,
                                                     RevisionCycleItem.status == "PROPOSED").count()
    if not proposed:
        raise bad_request("The cycle proposes no change.", "CYCLE_EMPTY")
    makers = sorted({u for u in (cycle.created_by_user_id, principal.user_id) if u is not None})
    request = approvals.submit(db, principal, module=comp_service.MODULE, subject_type=SUBJECT, subject_id=cycle.id,
                               context={"maker_user_ids": makers, "effective_from": cycle.effective_from.isoformat(),
                                        "employees": proposed})
    cycle.status = "PENDING_APPROVAL"
    cycle.approval_request_id = request.id
    cycle.row_version += 1
    db.flush()
    _audit(db, principal, REVISION_CYCLE_SUBMITTED, f"Submitted the revision cycle {cycle.name} for approval", cycle,
           approval_request_id=request.id, employees=proposed)
    return cycle_json(db, cycle)


def decide_cycle(db: Session, principal: Principal, cycle_id: int, decision: str, remarks: str | None = None
                 ) -> dict[str, Any]:
    if not principal.has(comp_service.APPROVE):
        raise forbidden()
    cycle = db.query(RevisionCycle).filter(RevisionCycle.company_id == principal.company_id,
                                           RevisionCycle.id == cycle_id).first()
    if cycle is None:
        raise not_found("Revision cycle")
    request = approvals.pending_request(db, comp_service.MODULE, SUBJECT, cycle.id)
    if request is None:
        raise conflict("This cycle is not waiting for approval.", "NOT_PENDING")
    approvals.decide(db, principal, request.id, decision, remarks)
    db.refresh(cycle)
    return cycle_json(db, cycle)


@approvals.on_decided(comp_service.MODULE, SUBJECT)
def _on_decided(db: Session, principal: Principal | None, request) -> None:
    cycle = (db.query(RevisionCycle).filter(RevisionCycle.company_id == request.company_id,
                                            RevisionCycle.id == request.subject_id).with_for_update().first())
    if cycle is None or cycle.status != "PENDING_APPROVAL":
        return
    if request.status == approvals.APPROVED:
        if principal is not None and principal.employee_id is not None and db.query(RevisionCycleItem.id).filter(
                RevisionCycleItem.company_id == cycle.company_id, RevisionCycleItem.cycle_id == cycle.id,
                RevisionCycleItem.employee_id == principal.employee_id,
                RevisionCycleItem.status == "PROPOSED").first():
            raise forbidden("You cannot approve a revision cycle that changes your own salary.")
        cycle.status, action = "APPROVED", REVISION_CYCLE_APPROVED
    elif request.status == approvals.REJECTED:
        cycle.status, action = "REJECTED", REVISION_CYCLE_REJECTED
    else:
        cycle.status, action = "PREVIEWED", REVISION_CYCLE_CANCELLED
    cycle.row_version += 1
    db.flush()
    _audit(db, principal, action, f"Revision cycle {cycle.name}: {cycle.status.lower()}", cycle,
           approval_request_id=request.id)


def _approver(db: Session, cycle: RevisionCycle) -> int | None:
    from app.models.approvals import ApprovalRequest

    request = db.get(ApprovalRequest, cycle.approval_request_id) if cycle.approval_request_id else None
    if request is None:
        return None
    acted = [s.acted_by_user_id for s in request.steps if s.status == "approved" and s.acted_by_user_id]
    return acted[-1] if acted else None


def apply_cycle(db: Session, principal: Principal, cycle_id: int) -> dict[str, Any]:
    """Put an approved cycle's salaries in force; each item is re-validated, failures are recorded per item."""
    cycle = _load(db, principal, cycle_id, lock=True)
    if cycle.status != "APPROVED":
        raise conflict("Only an approved cycle can be applied.", "CYCLE_NOT_APPROVED")
    approver = _approver(db, cycle)
    if approver is None:
        raise conflict("The cycle has no recorded approver.", "CYCLE_NOT_APPROVED")
    cid = principal.company_id
    items = (db.query(RevisionCycleItem).filter(RevisionCycleItem.company_id == cid,
                                                RevisionCycleItem.cycle_id == cycle.id,
                                                RevisionCycleItem.status == "PROPOSED")
             .order_by(RevisionCycleItem.id).all())
    applied = failed = 0
    for item in items:
        proposed = item.proposed
        old = db.get(CompensationAssignment, item.old_assignment_id)
        try:
            with db.begin_nested():
                if not comp_service.can_edit_employee(db, principal, item.employee_id, cycle.effective_from):
                    raise not_found("Employee")
                checked = comp_service._validate(
                    db, principal, item.employee_id, template_version_id=proposed["template_version_id"],
                    pay_basis_amount=Decimal(proposed["pay_basis_amount"]), currency=proposed["currency"],
                    effective_from=cycle.effective_from, reason="REVISION",
                    overrides=comp_service.overrides_of(db, old) if proposed["template_version_id"] ==
                    old.template_version_id else {}, fx_rule=old.fx_rule)
                row = CompensationAssignment(
                    company_id=cid, employee_id=item.employee_id, assignment_id=checked["placement"].id,
                    template_version_id=proposed["template_version_id"],
                    pay_basis_amount=Decimal(proposed["pay_basis_amount"]), currency=checked["currency"],
                    fx_rule=checked["fx_rule"], effective_from=cycle.effective_from, reason="REVISION",
                    status="PENDING_APPROVAL", note=f"Revision cycle: {cycle.name}"[:1000], attachments=[],
                    split_period=comp_service._split_period(db, checked["placement"], cycle.effective_from),
                    revision_cycle_id=cycle.id, row_version=1,
                    created_by_user_id=cycle.created_by_user_id if cycle.created_by_user_id != approver
                    else principal.user_id, submitted_by_user_id=principal.user_id)
                db.add(row)
                db.flush()
                codes = {c.code: c.id for c in db.query(PayComponent).filter(
                    PayComponent.company_id == cid, PayComponent.code.in_(list(checked["overrides"]) or [""]))}
                for code, override in checked["overrides"].items():
                    (key, value), = override.items()
                    db.add(CompensationAssignmentLine(company_id=cid, compensation_assignment_id=row.id,
                                                      component_id=codes[code], **{key: value}))
                db.flush()
                comp_service.activate(db, principal, row, approved_by_user_id=approver)
            item.status, item.new_assignment_id, item.note = "APPLIED", row.id, None
            applied += 1
        except AppError as exc:
            detail = exc.detail if isinstance(exc.detail, dict) else {"message": exc.detail}
            item.status, item.note = "FAILED", f"{exc.code}: {detail.get('message')}"[:500]
            failed += 1
    cycle.status = "APPLIED"
    cycle.applied_by_user_id = principal.user_id
    cycle.applied_at = utcnow()
    cycle.row_version += 1
    db.flush()
    _audit(db, principal, REVISION_CYCLE_APPLIED, f"Applied the revision cycle {cycle.name}: {applied} applied, "
           f"{failed} failed", cycle, applied=applied, failed=failed, approved_by_user_id=approver)
    return cycle_json(db, cycle, items=True)
